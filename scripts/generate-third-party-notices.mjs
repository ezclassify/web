#!/usr/bin/env node
// Regenerate THIRD-PARTY-NOTICES.md from the direct production dependencies
// of the publishable workspaces. CI reruns this and diffs the result, so the
// committed file cannot drift from what the packages actually ship.
//
// Scope decisions, so the file stays meaningful and the CI diff stable:
//   - Direct production `dependencies` only. Transitive licenses are enforced
//     by the license-compliance CI step over the full production closure;
//     the notices file credits what we depend on directly.
//   - Peer dependencies are excluded: consumers provide them, we do not
//     redistribute them.
//   - @ezclassify/* siblings are excluded: first-party code, same license.
//   - Versions are the declared ranges from the workspace manifests, not the
//     installed versions, so a routine `npm install` float does not churn
//     the committed file.
//
// Usage: node scripts/generate-third-party-notices.mjs

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');

function readJson(file) {
    return JSON.parse(readFileSync(file, 'utf8'));
}

// Same discovery rule as verify-pack-consume.mjs: a workspace is publishable
// when its manifest does not carry `private: true`.
function discoverPublishableWorkspaces() {
    const rootManifest = readJson(path.join(REPO_ROOT, 'package.json'));
    const patterns = rootManifest.workspaces ?? [];
    const found = [];
    for (const pattern of patterns) {
        const dirs = pattern.endsWith('/*')
            ? readdirSync(path.join(REPO_ROOT, pattern.slice(0, -2)), {
                  withFileTypes: true,
              })
                  .filter((e) => e.isDirectory())
                  .map((e) => path.join(pattern.slice(0, -2), e.name))
            : [pattern];
        for (const dir of dirs) {
            const manifestPath = path.join(REPO_ROOT, dir, 'package.json');
            if (!existsSync(manifestPath)) continue;
            const manifest = readJson(manifestPath);
            if (manifest.private === true) continue;
            found.push({ dir, manifest });
        }
    }
    return found;
}

function installedManifest(name) {
    const p = path.join(REPO_ROOT, 'node_modules', name, 'package.json');
    return existsSync(p) ? readJson(p) : null;
}

function licenseText(name) {
    const dir = path.join(REPO_ROOT, 'node_modules', name);
    if (!existsSync(dir)) return null;
    const candidate = readdirSync(dir).find((f) =>
        /^(LICEN[CS]E|COPYING)(\.(md|txt))?$/i.test(f),
    );
    return candidate
        ? readFileSync(path.join(dir, candidate), 'utf8').trim()
        : null;
}

function repoUrl(manifest) {
    const repo = manifest?.repository;
    const raw = typeof repo === 'string' ? repo : repo?.url;
    if (!raw) return manifest?.homepage ?? null;
    const cleaned = raw
        .replace(/^git\+/, '')
        .replace(/\.git$/, '')
        .replace(/^git:\/\//, 'https://');
    // npm allows the "owner/repo" GitHub shorthand; expand it to a real URL.
    return /^[\w.-]+\/[\w.-]+$/.test(cleaned)
        ? `https://github.com/${cleaned}`
        : cleaned;
}

// dependency name -> { range, usedBy: [workspace names], manifest }
const deps = new Map();
for (const { manifest } of discoverPublishableWorkspaces()) {
    for (const [name, range] of Object.entries(manifest.dependencies ?? {})) {
        if (name.startsWith('@ezclassify/')) continue;
        const entry = deps.get(name) ?? { ranges: new Set(), usedBy: [] };
        entry.ranges.add(range);
        entry.usedBy.push(manifest.name);
        deps.set(name, entry);
    }
}

const lines = [
    '# Third-Party Notices',
    '',
    'This file lists the third-party packages that the publishable',
    '`@ezclassify` JavaScript packages depend on directly at runtime, with their',
    'licenses. It is generated by `scripts/generate-third-party-notices.mjs`',
    'and checked in CI; regenerate it with `npm run notices` after changing',
    'a production dependency.',
    '',
];

const names = [...deps.keys()].sort();
if (names.length === 0) {
    lines.push('The publishable packages currently have no third-party');
    lines.push('production dependencies.');
} else {
    for (const name of names) {
        const entry = deps.get(name);
        const installed = installedManifest(name);
        if (!installed) {
            console.error(
                `ERROR: ${name} is not installed; run npm install first.`,
            );
            process.exit(1);
        }
        lines.push('---');
        lines.push('');
        lines.push(`## ${name}`);
        lines.push('');
        lines.push(`- Version range: ${[...entry.ranges].sort().join(', ')}`);
        lines.push(`- License: ${installed.license ?? 'UNKNOWN'}`);
        const url = repoUrl(installed);
        if (url) lines.push(`- Source: ${url}`);
        lines.push(`- Used by: ${entry.usedBy.sort().join(', ')}`);
        const text = licenseText(name);
        if (text) {
            lines.push('');
            lines.push('```text');
            lines.push(text);
            lines.push('```');
        }
        lines.push('');
    }
}

const out = lines.join('\n').replace(/\n+$/, '\n');
writeFileSync(path.join(REPO_ROOT, 'THIRD-PARTY-NOTICES.md'), out);
console.log(
    `THIRD-PARTY-NOTICES.md written (${names.length} third-party package${
        names.length === 1 ? '' : 's'
    }).`,
);
